export const FONT_HEIGHT = 5;
const LETTER_SPACING = 1;

function glyph(ch: string): string[] {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
}

export function measureText(str: string): number {
  let w = 0;
  for (const ch of str) w += glyph(ch)[0].length + LETTER_SPACING;
  return Math.max(0, w - LETTER_SPACING);
}

export function drawText(pc: PixelCanvas, str: string, x: number, y: number, c: number): void {
  let cx = x;
  for (const ch of str) {
    const g = glyph(ch);
    for (let row = 0; row < g.length; row++) {
      const line = g[row];
      for (let col = 0; col < line.length; col++) if (line[col] === '#') pc.set(cx + col, y + row, c);
    }
    cx += g[0].length + LETTER_SPACING;
  }
}
